// Generates components/examples/registry.ts from every *.tsx example file.
// Run after adding or removing example files:  node scripts/gen-example-registry.mjs
// Agents never edit registry.ts by hand — this keeps it conflict-free.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const examplesDir = join(here, "..", "components", "examples");

const files = readdirSync(examplesDir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort();

const pascal = (name) =>
  name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const imports = files
  .map((name) => `import ${pascal(name)} from "./${name}";`)
  .join("\n");

const entries = files
  .map((name) => `  "${name}": ${pascal(name)},`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-example-registry.mjs — do not edit by hand.
import type { ComponentType } from "react";

${imports}

export const exampleRegistry: Record<string, ComponentType> = {
${entries}
};

export type ExampleName = keyof typeof exampleRegistry;
`;

writeFileSync(join(examplesDir, "registry.ts"), out);
console.log(`Generated registry with ${files.length} examples.`);
